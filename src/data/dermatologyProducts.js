export function getDermatologyProductBySlug(slug) {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim();
  const cleanNormalized = normalized.replace(/[^a-z0-9]/g, '');

  return dermatologyProducts.find(p => {
    const pSlug = p.slug.toLowerCase();
    const pName = p.name.toLowerCase().replace(/\s+/g, '-');
    const cleanPSlug = pSlug.replace(/[^a-z0-9]/g, '');
    const cleanPName = pName.replace(/[^a-z0-9]/g, '');

    return pSlug === normalized ||
           pName === normalized ||
           cleanPSlug === cleanNormalized ||
           cleanPName === cleanNormalized;
  }) || null;
}
