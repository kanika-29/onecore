export function getAreaBySlug(slug) {
  if (!slug) return null;
  const cleaned = slug.toLowerCase().trim();
  return (
    areasOfCare.find(
      (area) =>
        area.slug === cleaned ||
        area.id === cleaned ||
        (area.aliases && area.aliases.includes(cleaned))
    ) || null
  );
}

export function getAllAreas() {
  return areasOfCare;
}

